const SCHEDULE_DAYS = 14;
const PASSWORD_KEYS = [
  'SEED_SUPER_ADMIN_PASSWORD',
  'SEED_MANAGER_PASSWORD',
  'SEED_CUSTOMER_PASSWORD',
] as const;
const webPublicDir = fileURLToPath(new URL('../../../web/public/', import.meta.url));

/** Deterministic UUID (version 5 layout) for seed rows without a natural key. */
function seedId(name: string): string {
  const hex = createHash('sha1').update(`kinemax-seed:${name}`).digest('hex');
  const variant = ((parseInt(hex.charAt(16), 16) & 0x3) | 0x8).toString(16);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-${variant}${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}

function randomPassword(length = 24): string {
  const alphabet = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789';
  return Array.from({ length }, () => alphabet.charAt(randomInt(alphabet.length))).join('');
}

/**
 * Makes sure every SEED_* password exists in .env, generating missing ones. An empty `KEY=` line
 * (as copied from .env.example) is filled in place; otherwise the key is appended. Never prints them.
 */
function ensureSeedPasswords(): Record<(typeof PASSWORD_KEYS)[number], string> {
  const missing = PASSWORD_KEYS.filter((key) => !process.env[key]);
  if (missing.length > 0) {
    if (!existsSync(rootEnvPath)) throw new Error('.env not found; copy .env.example first.');
    let content = readFileSync(rootEnvPath, 'utf8');
    const appended: string[] = [];
    for (const key of missing) {
      const value = randomPassword();
      process.env[key] = value;
      const emptyLine = new RegExp(`^${key}=[ \\t]*$`, 'm');
      if (emptyLine.test(content)) content = content.replace(emptyLine, `${key}=${value}`);
      else appended.push(`${key}=${value}`);
    }
    if (appended.length > 0) {
      const prefix = content === '' || content.endsWith('\n') ? '' : '\n';
      content += `${prefix}# Dev-only demo user passwords (generated by db:seed)\n${appended.join('\n')}\n`;
    }
    writeFileSync(rootEnvPath, content);
    console.info(`Generated ${String(missing.length)} demo password(s) into .env (not shown).`);
  }
  return Object.fromEntries(PASSWORD_KEYS.map((key) => [key, process.env[key] ?? ''])) as Record<
    (typeof PASSWORD_KEYS)[number],
    string
  >;
}

async function upsertUser(
  prisma: PrismaClient,
  user: {
    email: string;
    name: string;
    role: 'CUSTOMER' | 'LOCATION_MANAGER' | 'SUPER_ADMIN';
    preferredLocale?: 'sq' | 'en';
  },
  password: string,
): Promise<string> {
  const email = user.email.trim().toLowerCase();
  const existing = await prisma.user.findUnique({ where: { email } });
  const passwordHash =
    existing && (await verifyPassword(existing.passwordHash, password))
      ? existing.passwordHash
      : await hashPassword(password);
  const data = {
    name: user.name,
    role: user.role,
    preferredLocale: user.preferredLocale ?? 'sq',
    isActive: true,
    passwordHash,
  };
  const saved = await prisma.user.upsert({
    where: { email },
    create: { email, ...data },
    update: data,
  });
  return saved.id;
}

function writeArtwork(): void {
  for (const dir of ['seed/posters', 'seed/backdrops'])
    mkdirSync(`${webPublicDir}${dir}`, { recursive: true });
  for (const movie of MOVIES) {
    writeFileSync(`${webPublicDir}seed/posters/${movie.slug}.svg`, posterSvg(movie));
    writeFileSync(`${webPublicDir}seed/backdrops/${movie.slug}.svg`, backdropSvg(movie));
  }
}

async function seedCatalog(prisma: PrismaClient) {
  const hallTypeIds = new Map<string, string>();
  for (const type of HALL_TYPES) {
    const { code, ...data } = type;
    const saved = await prisma.hallType.upsert({ where: { code }, create: type, update: data });
    hallTypeIds.set(code, saved.id);
  }

  const locationIds = new Map<string, string>();
  const halls: { id: string; key: string; type: string; index: number; locationSlug: string }[] =
    [];
  for (const location of LOCATIONS) {
    const data = {
      name: location.name,
      city: location.city,
      address: location.address,
      timeZone: TIME_ZONE,
      isActive: true,
    };
    const saved = await prisma.location.upsert({
      where: { slug: location.slug },
      create: { slug: location.slug, ...data },
      update: data,
    });
    locationIds.set(location.slug, saved.id);

    for (const [index, hall] of location.halls.entries()) {
      const hallData = {
        hallTypeId: hallTypeIds.get(hall.type) ?? '',
        isActive: true,
        wholeHallOnly: hall.type === 'PRIVATE_SUITE',
        screenWidthM: hall.screen.widthM,
        screenHeightM: hall.screen.heightM,
        screenX: 0,
        screenY: 0,
        screenZ: hall.screen.z,
      };
      const savedHall = await prisma.hall.upsert({
        where: { locationId_name: { locationId: saved.id, name: hall.name } },
        create: { locationId: saved.id, name: hall.name, ...hallData },
        update: hallData,
      });
      halls.push({
        id: savedHall.id,
        key: `${location.slug}/${hall.name}`,
        type: hall.type,
        index,
        locationSlug: location.slug,
      });
      await syncSeats(prisma, savedHall.id, generateSeats(hall.layout));

      if (hall.wholeHallPriceCents !== undefined) {
        const id = seedId(`whole-hall-price:${location.slug}/${hall.name}`);
        const priceData = {
          hallId: savedHall.id,
          priceCents: hall.wholeHallPriceCents,
          validFrom: RULES_VALID_FROM,
          validTo: null,
          isActive: true,
        };
        await prisma.wholeHallPrice.upsert({
          where: { id },
          create: { id, ...priceData },
          update: priceData,
        });
      }
    }
  }
  return { hallTypeIds, locationIds, halls };
}

/** Inserts new seats, updates changed ones and removes seats that left the layout (if unused). */
async function syncSeats(
  prisma: PrismaClient,
  hallId: string,
  seats: ReturnType<typeof generateSeats>,
) {
  const existing = await prisma.seat.findMany({ where: { hallId } });
  const byKey = new Map(existing.map((seat) => [`${seat.rowLabel}-${String(seat.number)}`, seat]));
  const wanted = new Set<string>();
  const toCreate = [];
  for (const seat of seats) {
    const key = `${seat.rowLabel}-${String(seat.number)}`;
    wanted.add(key);
    const current = byKey.get(key);
    const data = { ...seat, hallId, isActive: true };
    if (!current) toCreate.push(data);
    else if (
      current.seatType !== seat.seatType ||
      current.x !== seat.x ||
      current.y !== seat.y ||
      current.z !== seat.z ||
      current.rotationDeg !== seat.rotationDeg ||
      current.widthUnits !== seat.widthUnits ||
      !current.isActive
    ) {
      await prisma.seat.update({ where: { id: current.id }, data });
    }
  }
  if (toCreate.length > 0) await prisma.seat.createMany({ data: toCreate });
  const removed = existing.filter((seat) => !wanted.has(`${seat.rowLabel}-${String(seat.number)}`));
  for (const seat of removed) {
    const used = await prisma.bookingSeat.count({ where: { seatId: seat.id } });
    if (used > 0) await prisma.seat.update({ where: { id: seat.id }, data: { isActive: false } });
    else await prisma.seat.delete({ where: { id: seat.id } });
  }
}

async function seedMovies(prisma: PrismaClient) {
  writeArtwork();
  const ids = new Map<string, string>();
  for (const movie of MOVIES) {
    const data = {
      ...movie,
      releaseDate: new Date(`${movie.releaseDate}T00:00:00Z`),
      posterPath: `/seed/posters/${movie.slug}.svg`,
      backdropPath: `/seed/backdrops/${movie.slug}.svg`,
      trailerYoutubeId: null,
    };
    const saved = await prisma.movie.upsert({
      where: { slug: movie.slug },
      create: data,
      update: data,
    });
    ids.set(movie.slug, saved.id);
  }
  return ids;
}

async function seedShowtimes(
  prisma: PrismaClient,
  halls: { id: string; key: string; type: string; index: number }[],
  movieIds: Map<string, string>,
) {
  const today = toLocalDateTime(new Date(), TIME_ZONE).date;
  const dates = Array.from({ length: SCHEDULE_DAYS }, (_, i) => addDays(today, i));
  const windowStart = zonedTimeToUtc(today, 0, TIME_ZONE);
  const windowEnd = zonedTimeToUtc(addDays(today, SCHEDULE_DAYS), 0, TIME_ZONE);
  const nowShowing = MOVIES.filter((movie) => movie.status === 'NOW_SHOWING');
  const plan = planShowtimes({
    halls: halls.map((h): ScheduleHall => ({
      key: h.key,
      type: h.type as ScheduleHall['type'],
      index: h.index,
    })),
    movies: nowShowing,
    dates,
  });

  let created = 0;
  for (const hall of halls) {
    const planned = plan
      .filter((p) => p.hallKey === hall.key)
      .map((p) => {
        const startsAt = zonedTimeToUtc(p.date, p.startMinute, TIME_ZONE);
        return {
          hallId: hall.id,
          movieId: movieIds.get(p.movieSlug) ?? '',
          startsAt,
          endsAt: new Date(startsAt.getTime() + p.blockMinutes * 60_000),
          format: p.format,
          languageVersion: p.languageVersion,
          isActive: true,
        };
      });
    const plannedByStart = new Map(planned.map((p) => [p.startsAt.toISOString(), p]));
    const existing = await prisma.showtime.findMany({
      where: { hallId: hall.id, startsAt: { gte: windowStart, lt: windowEnd } },
      include: { _count: { select: { bookings: true } } },
    });

    // Remove stale demo showtimes first (only if nobody booked them), so new ones cannot overlap.
    for (const show of existing) {
      if (!plannedByStart.has(show.startsAt.toISOString()) && show._count.bookings === 0) {
        await prisma.showtime.delete({ where: { id: show.id } });
      }
    }
    const kept = new Set(existing.map((s) => s.startsAt.toISOString()));
    for (const show of existing) {
      const wanted = plannedByStart.get(show.startsAt.toISOString());
      if (wanted && show._count.bookings === 0) {
        await prisma.showtime.update({ where: { id: show.id }, data: wanted });
      }
    }
    const toCreate = planned.filter((p) => !kept.has(p.startsAt.toISOString()));
    if (toCreate.length > 0) {
      await prisma.showtime.createMany({ data: toCreate });
      created += toCreate.length;
    }
  }
  return { planned: plan.length, created, from: today, to: addDays(today, SCHEDULE_DAYS - 1) };
}

async function seedPricing(
  prisma: PrismaClient,
  hallTypeIds: Map<string, string>,
  locationIds: Map<string, string>,
) {
  for (const rule of BASE_PRICES) {
    const id = seedId(`hall-type-price:${rule.hallType}:${rule.locationSlug ?? 'all'}`);
    const data = {
      hallTypeId: hallTypeIds.get(rule.hallType) ?? '',
      locationId: rule.locationSlug ? (locationIds.get(rule.locationSlug) ?? null) : null,
      priceCents: rule.priceCents,
      validFrom: RULES_VALID_FROM,
      validTo: null,
      isActive: true,
    };
    await prisma.hallTypePrice.upsert({ where: { id }, create: { id, ...data }, update: data });
  }
  for (const rule of SEAT_SURCHARGES) {
    const id = seedId(`seat-surcharge:${rule.seatType}`);
    const data = { ...rule, validFrom: RULES_VALID_FROM, validTo: null, isActive: true };
    await prisma.seatTypeSurcharge.upsert({ where: { id }, create: { id, ...data }, update: data });
  }
  for (const { key, ...rule } of TIME_ADJUSTMENTS) {
    const id = seedId(`time-adjustment:${key}`);
    const data = {
      ...rule,
      locationId: null,
      validFrom: RULES_VALID_FROM,
      validTo: null,
      isActive: true,
    };
    await prisma.timePriceAdjustment.upsert({
      where: { id },
      create: { id, ...data },
      update: data,
    });
  }
  for (const { discount, ...category } of TICKET_CATEGORIES) {
    const { code, ...data } = category;
    const saved = await prisma.ticketCategory.upsert({
      where: { code },
      create: category,
      update: data,
    });
    if (discount) {
      const id = seedId(`category-discount:${code}`);
      const rule = {
        ticketCategoryId: saved.id,
        ...discount,
        validFrom: RULES_VALID_FROM,
        validTo: null,
        isActive: true,
      };
      await prisma.ticketCategoryDiscount.upsert({
        where: { id },
        create: { id, ...rule },
        update: rule,
      });
    }
  }
}

async function seedMenu(prisma: PrismaClient, locationIds: Map<string, string>) {
  const ids = new Map<string, string>();
  for (const item of MENU_ITEMS) {
    const data = {
      slug: item.slug,
      nameSq: item.nameSq,
      nameEn: item.nameEn,
      descriptionSq: item.descriptionSq ?? null,
      descriptionEn: item.descriptionEn ?? null,
      category: item.category,
      isCombo: item.category === 'COMBO',
      isActive: true,
      imagePath: null,
    };
    const saved = await prisma.menuItem.upsert({
      where: { slug: item.slug },
      create: data,
      update: data,
    });
    ids.set(item.slug, saved.id);
  }
  for (const item of MENU_ITEMS.filter((i) => i.components)) {
    const comboId = ids.get(item.slug) ?? '';
    await prisma.comboComponent.deleteMany({ where: { comboId } });
    await prisma.comboComponent.createMany({
      data: (item.components ?? []).map((c) => ({
        comboId,
        componentId: ids.get(c.slug) ?? '',
        quantity: c.quantity,
      })),
    });
  }
  for (const [slug, menu] of Object.entries(LOCATION_MENUS)) {
    const locationId = locationIds.get(slug) ?? '';
    for (const item of MENU_ITEMS) {
      const menuItemId = ids.get(item.slug) ?? '';
      const priceCents = Math.round((item.priceCents * menu.priceFactor) / 10) * 10;
      const isAvailable = !menu.unavailable.includes(item.slug);
      const where = { locationId_menuItemId: { locationId, menuItemId } };
      if (isAvailable) {
        await prisma.locationMenuItem.upsert({
          where,
          create: { locationId, menuItemId, priceCents, isAvailable },
          update: { priceCents, isAvailable },
        });
      } else {
        await prisma.locationMenuItem.updateMany({
          where: { locationId, menuItemId },
          data: { isAvailable: false },
        });
      }
    }
  }
}

async function seedUsers(prisma: PrismaClient, locationIds: Map<string, string>) {
  const passwords = ensureSeedPasswords();
  await upsertUser(
    prisma,
    { ...SEED_USERS.superAdmin, role: 'SUPER_ADMIN' },
    passwords.SEED_SUPER_ADMIN_PASSWORD,
  );
  for (const manager of SEED_USERS.managers) {
    const userId = await upsertUser(
      prisma,
      { ...manager, role: 'LOCATION_MANAGER' },
      passwords.SEED_MANAGER_PASSWORD,
    );
    const locationId = locationIds.get(manager.locationSlug) ?? '';
    await prisma.managerLocation.upsert({
      where: { userId_locationId: { userId, locationId } },
      create: { userId, locationId },
      update: {},
    });
  }
  for (const customer of SEED_USERS.customers) {
    await upsertUser(prisma, { ...customer, role: 'CUSTOMER' }, passwords.SEED_CUSTOMER_PASSWORD);
  }
}

async function printSummary(
  prisma: PrismaClient,
  showtimes: Awaited<ReturnType<typeof seedShowtimes>>,
) {
  const [locations, halls, seats, movies, showtimeCount, menuItems, users] = await Promise.all([
    prisma.location.count(),
    prisma.hall.groupBy({ by: ['hallTypeId'], _count: { _all: true } }),
    prisma.seat.groupBy({ by: ['seatType'], _count: { _all: true } }),
    prisma.movie.groupBy({ by: ['status'], _count: { _all: true } }),
    prisma.showtime.count(),
    prisma.menuItem.count(),
    prisma.user.groupBy({ by: ['role'], _count: { _all: true } }),
  ]);
  const types = new Map((await prisma.hallType.findMany()).map((t) => [t.id, t.code]));
  const fmt = (rows: { key: string; count: number }[]) =>
    rows.map((r) => `${r.key}=${String(r.count)}`).join(', ');
  console.info('Seed complete:');
  console.info(`  locations: ${String(locations)}`);
  console.info(
    `  halls: ${fmt(halls.map((h) => ({ key: types.get(h.hallTypeId) ?? '?', count: h._count._all })))}`,
  );
  console.info(`  seats: ${fmt(seats.map((s) => ({ key: s.seatType, count: s._count._all })))}`);
  console.info(`  movies: ${fmt(movies.map((m) => ({ key: m.status, count: m._count._all })))}`);
  console.info(
    `  showtimes: ${String(showtimeCount)} total (${String(showtimes.planned)} planned for ${showtimes.from}..${showtimes.to}, ${String(showtimes.created)} new)`,
  );
  console.info(`  menu items: ${String(menuItems)}`);
  console.info(`  users: ${fmt(users.map((u) => ({ key: u.role, count: u._count._all })))}`);
}

async function main() {
  loadDotEnv(rootEnvPath);
  if (process.env.NODE_ENV === 'production')
    throw new Error('Refusing to seed with NODE_ENV=production.');
  const { url, name } = assertDevelopmentDatabaseUrl(process.env.DATABASE_URL);
  console.info(`Seeding development database "${name}"...`);

  const prisma = createPrismaClient(url);
  try {
    const { hallTypeIds, locationIds, halls } = await seedCatalog(prisma);
    const movieIds = await seedMovies(prisma);
    await seedPricing(prisma, hallTypeIds, locationIds);
    await seedMenu(prisma, locationIds);
    await seedUsers(prisma, locationIds);
    const showtimes = await seedShowtimes(prisma, halls, movieIds);
    await printSummary(prisma, showtimes);
  } finally {
    await prisma.$disconnect();
  }
}

main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
});
